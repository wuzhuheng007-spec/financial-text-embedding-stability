  function translate(value, depth) {
    const raw = String(value == null ? '' : value);
    if (!han.test(raw)) return raw;
    const trimmed = raw.trim();
    if (Object.prototype.hasOwnProperty.call(catalog, trimmed)) return raw.replace(trimmed, catalog[trimmed]);
    for (const [rule, render] of patterns) {
      const match = trimmed.match(rule);
      if (match) { const out = render(...match); if (!han.test(out)) return raw.replace(trimmed, out); }
    }
    // Composition from catalog pieces, longest first. A marker around each piece lets two pieces that end up
    // side by side (or a piece next to a literal word or number) be separated by one space instead of fusing.
    let out = raw;
    for (const [zh, en] of entries) if (out.includes(zh)) out = out.split(zh).join(M + en + M);
    if (!han.test(out)) out = out.replace(GLUE, '$1 $2').split(M).join('').replace(/ {2,}/g, ' ');
    if (!han.test(out)) return out;
    // A compound sentence ("label：a；b · c") whose parts are covered one by one. Every part must translate
    // completely, otherwise the whole string is left as it is.
    if ((depth || 0) < 3) {
      for (const [sep, joiner] of SEPARATORS) {
        const at = trimmed.indexOf(sep);
        if (at <= 0 || at >= trimmed.length - sep.length) continue;
        const parts = sep === '：' ? [trimmed.slice(0, at), trimmed.slice(at + 1)] : trimmed.split(sep);
        const done = parts.map(p => translate(p, (depth || 0) + 1));
        if (done.every(p => !han.test(p))) return raw.replace(trimmed, done.map((p, i) => i ? p.replace(/^ +/, '') : p).join(joiner).replace(/ {2,}/g, ' '));
      }
    }
    // Never hide a missing sentence by deleting or partially translating it: audit() reports it.
    return raw;
  }

